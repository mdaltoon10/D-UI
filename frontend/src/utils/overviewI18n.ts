export function getStatTranslations(lang?: string): StatTranslations {
  if (!lang) return translationsMap['en'];

  // Exact match (e.g. 'zh-CN', 'zh-TW', 'pt-BR')
  if (translationsMap[lang]) {
    return translationsMap[lang];
  }

  // Language code prefix (e.g. 'zh' from 'zh-CN', 'fa' from 'fa-IR', 'ar' from 'ar-EG')
  const prefix = lang.split('-')[0].toLowerCase();
  if (translationsMap[prefix]) {
    return translationsMap[prefix];
  }

  return translationsMap['en'];
}
