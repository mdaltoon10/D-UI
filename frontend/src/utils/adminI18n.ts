export function getAdminTranslations(lang?: string): AdminTranslations {
  if (!lang) return adminTranslationsMap['en'];

  if (adminTranslationsMap[lang]) {
    return adminTranslationsMap[lang];
  }

  const prefix = lang.split('-')[0].toLowerCase();
  if (adminTranslationsMap[prefix]) {
    return adminTranslationsMap[prefix];
  }

  return adminTranslationsMap['en'];
}
